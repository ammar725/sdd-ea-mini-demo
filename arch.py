#!/usr/bin/env python3
"""
SDD architecture checker for the HR Policy Assistant demo.

  python arch.py check      Check traceability AND architecture conformance (default)
  python arch.py reset      Restore sdd/ to the demo starting state
  python arch.py solution   Load the finished RULE-03 version (presenter fallback)

Traceability:  RULE -> REQ -> CTRL (@component, ADR) -> TASK -> VAL
Conformance:   each rule's check (fitness function) runs against the architecture model in spec.md
Diagram:       architecture-diagram.md is regenerated (Mermaid) on every check

No dependencies. Python 3.8+.
"""
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SDD = ROOT / "sdd"
FILES = ["constitution.md", "spec.md", "tasks.md", "validation.md"]
DIAGRAM = ROOT / "architecture-diagram.md"
ADR_STATUSES = ("proposed", "accepted", "superseded", "rejected")

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if os.name == "nt":
    os.system("")
GREEN, YELLOW, RED, DIM, BOLD, RESET = (
    "\033[32m", "\033[33m", "\033[31m", "\033[2m", "\033[1m", "\033[0m")


# ---------------------------------------------------------------- reading

def read_tables(filename):
    """All markdown tables in a file, as (headers, rows-as-dicts)."""
    out, header = [], None
    for line in (SDD / filename).read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s.startswith("|"):
            header = None
            continue
        cells = [re.sub(r"\*\*|🆕|`", "", c).strip() for c in s.strip("|").split("|")]
        if all(set(c) <= set("-: ") for c in cells):
            continue
        if header is None:
            header = [c.lower() for c in cells]
            out.append((header, []))
            continue
        out[-1][1].append(dict(zip(header, cells)))
    return out


def table(filename, *cols, prefix=None):
    """Rows of the first table that has all `cols`; optionally only IDs with `prefix`."""
    for header, rows in read_tables(filename):
        if all(c in header for c in cols):
            if prefix:
                rows = [r for r in rows if re.fullmatch(prefix + r"-\d+", r.get("id", ""))]
            return [r for r in rows if r.get("id") and r["id"] != "—"]
    return []


def ids(text, prefix):
    return re.findall(prefix + r"-\d+", text or "")


# ---------------------------------------------------------------- fitness functions
# Each rule in constitution.md names one of these checks. They run against the model.

def make_checks(zones, comps, flows):
    def trust(cid):
        return zones.get(comps.get(cid, {}).get("zone"), {}).get("trust", "").lower()

    def ctype(cid):
        return comps.get(cid, {}).get("type", "").lower()

    return {
        "no-personal-data-external": (
            "personal data flows to an untrusted zone",
            lambda: [f for f in flows if trust(f["to"]) == "untrusted"
                     and f.get("data", "").lower() == "personal"]),
        "ai-read-only": (
            "AI component writes to a system of record",
            lambda: [f for f in flows if ctype(f["from"]) in ("ai-app", "agent")
                     and ctype(f["to"]) == "system-of-record"
                     and f.get("access", "").lower() != "read"]),
        "external-ai-via-gateway": (
            "calls an external AI model without going through the AI gateway",
            lambda: [f for f in flows if ctype(f["to"]) == "ai-model"
                     and trust(f["to"]) == "untrusted" and ctype(f["from"]) != "gateway"]),
    }


# ---------------------------------------------------------------- diagram

def write_diagram(zones, comps, flows, violations):
    nid = lambda c: re.sub(r"\W", "_", c)
    lines = ["# Architecture diagram — HR Policy Assistant", "",
             "> Generated by `arch.py` from the architecture model in `sdd/spec.md`. Do not edit.", "",
             "```mermaid", "flowchart LR"]
    for zid, z in zones.items():
        lines.append(f'  subgraph {nid(zid)}["{z.get("name", zid)} - {z.get("trust", "")}"]')
        for cid, c in comps.items():
            if c.get("zone") == zid:
                lines.append(f'    {nid(cid)}["{c.get("name", cid)}<br/><small>{c.get("type", "")}</small>"]')
        lines.append("  end")
    red = []
    for i, f in enumerate(flows):
        label = f'{f["id"]}: {f.get("data", "")}, {f.get("access", "")}'
        if f["id"] in violations:
            label = f'VIOLATES {", ".join(violations[f["id"]])} - {label}'
            red.append(i)
        lines.append(f'  {nid(f["from"])} -->|"{label}"| {nid(f["to"])}')
    for i in red:
        lines.append(f"  linkStyle {i} stroke:#d62728,stroke-width:3px,color:#d62728")
    gw = [nid(c) for c, v in comps.items() if v.get("type") == "gateway"]
    if gw:
        lines.append("  classDef gateway fill:#dbeafe,stroke:#1d4ed8,stroke-width:2px")
        lines.append(f"  class {','.join(gw)} gateway")
    untrusted = [nid(z) for z, v in zones.items() if v.get("trust") == "untrusted"]
    for z in untrusted:
        lines.append(f"  style {z} fill:#fff5f5,stroke:#d62728,stroke-dasharray: 5 5")
    lines += ["```", ""]
    DIAGRAM.write_text("\n".join(lines), encoding="utf-8")


# ---------------------------------------------------------------- check

def check():
    for f in FILES:
        if not (SDD / f).exists():
            print(f"{RED}Missing sdd/{f}{RESET}")
            return 1

    rules = table("constitution.md", "id", "rule", "check", prefix="RULE")
    zones = {z["id"]: z for z in table("spec.md", "id", "name", "trust")}
    comps = {c["id"]: c for c in table("spec.md", "id", "name", "type", "zone")}
    flows = table("spec.md", "id", "from", "to", "data")
    reqs = table("spec.md", "id", "requirement", "rule", prefix="REQ")
    adrs = {a["id"]: a for a in table("spec.md", "id", "decision", "status", prefix="ADR")}
    ctrls = table("spec.md", "id", "control", "requirement", "enforced at", prefix="CTRL")
    tasks = table("tasks.md", "id", "task", "control", "status", prefix="TASK")
    vals = table("validation.md", "id", "control", "result", prefix="VAL")

    checks = make_checks(zones, comps, flows)
    problems = []

    # --- model and reference integrity
    for c in comps.values():
        if c.get("zone") not in zones:
            problems.append(f"Component {c['id']} is in unknown zone '{c.get('zone')}'")
    for f in flows:
        for end in ("from", "to"):
            if f.get(end) not in comps:
                problems.append(f"Flow {f['id']} {end} '{f.get(end)}' is not a component in the architecture model")
    rule_ids = {r["id"] for r in rules}
    req_ids = {r["id"] for r in reqs}
    ctrl_ids = {c["id"] for c in ctrls}
    for r in rules:
        chk = r.get("check", "—")
        if chk not in ("—", "") and chk not in checks:
            problems.append(f"{r['id']} names unknown check '{chk}' (known: {', '.join(checks)})")
    for r in reqs:
        problems += [f"{r['id']} points to {x}, which is not in constitution.md"
                     for x in ids(r.get("rule"), "RULE") if x not in rule_ids]
    for c in ctrls:
        problems += [f"{c['id']} points to {x}, which is not in spec.md"
                     for x in ids(c.get("requirement"), "REQ") if x not in req_ids]
        if c.get("enforced at") not in comps:
            problems.append(f"{c['id']} is enforced at '{c.get('enforced at')}', "
                            f"which is not a component in the architecture model (control and design have drifted)")
        problems += [f"{c['id']} cites {x}, which is not in the decisions table"
                     for x in ids(c.get("adr"), "ADR") if x not in adrs]
    for t in tasks:
        problems += [f"{t['id']} points to {x}, which is not in spec.md"
                     for x in ids(t.get("control"), "CTRL") if x not in ctrl_ids]
    for v in vals:
        problems += [f"{v['id']} points to {x}, which is not in spec.md"
                     for x in ids(v.get("control"), "CTRL") if x not in ctrl_ids]

    cited = {a for c in ctrls for a in ids(c.get("adr"), "ADR")}
    for a in adrs.values():
        if a["id"] not in cited and a.get("status", "").lower() not in ADR_STATUSES:
            problems.append(f"{a['id']} status '{a.get('status', '')}' isn't valid. "
                            f"Use {', '.join(s.title() for s in ADR_STATUSES)}")

    linked = lambda rows, col, target: [
        r for r in rows if target in ids(r.get(col), target.split("-")[0])]

    # --- per-rule evaluation
    print(f"\n{BOLD}SDD architecture check — HR Policy Assistant{RESET}\n")
    print(f"{DIM}{'RULE':<9}{'REQ':<9}{'CTRL':<10}{'TASK':<10}{'VAL':<9}{'ARCH':<6}STATUS{RESET}")

    violations_by_flow = {}
    counts = {"ok": 0, "proposed": 0, "broken": 0}
    for rule in rules:
        rid = rule["id"]
        r_reqs = linked(reqs, "rule", rid)
        r_ctrls = [c for q in r_reqs for c in linked(ctrls, "requirement", q["id"])]
        r_tasks = [t for c in r_ctrls for t in linked(tasks, "control", c["id"])]
        r_vals = [v for c in r_ctrls for v in linked(vals, "control", c["id"])]

        gaps, pending = [], []
        if not r_reqs:
            gaps.append("no requirement in spec.md")
        for q in r_reqs:
            if not linked(ctrls, "requirement", q["id"]):
                gaps.append(f"{q['id']} has no control in spec.md")
        for c in r_ctrls:
            c_vals = linked(vals, "control", c["id"])
            if not linked(tasks, "control", c["id"]):
                gaps.append(f"{c['id']} has no task in tasks.md")
            if not c_vals:
                gaps.append(f"{c['id']} has no validation in validation.md")
            if c.get("enforced at") not in comps:
                gaps.append(f"{c['id']} is enforced at a component that does not exist")
            for a in ids(c.get("adr"), "ADR"):
                if a not in adrs:
                    continue
                st = adrs[a].get("status", "")
                if st.lower() not in ADR_STATUSES:
                    gaps.append(f"{a} status '{st}' isn't valid. Use {', '.join(s.title() for s in ADR_STATUSES)}")
                elif st.lower() in ("superseded", "rejected"):
                    gaps.append(f"{c['id']} relies on {a}, which is {st}")
                elif st.lower() == "proposed":
                    pending.append(f"{a} is Proposed")
            passed = c_vals and all(v.get("result", "").lower() == "pass" for v in c_vals)
            for t in linked(tasks, "control", c["id"]):
                if t.get("status", "").lower() == "done" and not passed:
                    gaps.append(f"{t['id']} is marked Done, but its validation has not passed")
                elif t.get("status", "").lower() != "done":
                    pending.append(f"{t['id']} {t.get('status', 'not started').lower()}")

        # architecture conformance
        arch = "—"
        chk = rule.get("check", "—")
        if chk in checks:
            desc, fn = checks[chk]
            bad = fn()
            arch = "❌" if bad else "✅"
            for f in bad:
                violations_by_flow.setdefault(f["id"], []).append(rid)
                gaps.append(f"architecture: {f['id']} {f['from']} → {f['to']} {desc}")

        results = [v.get("result", "").lower() for v in r_vals]
        if any(r == "fail" for r in results):
            gaps.append("a validation failed")
        if r_vals and not all(r == "pass" for r in results):
            pending.append("validation not run")

        if gaps:
            status, key = f"{RED}❌ Broken{RESET}", "broken"
        elif pending:
            status, key = f"{YELLOW}⏳ Proposed — {'; '.join(dict.fromkeys(pending))}{RESET}", "proposed"
        else:
            status, key = f"{GREEN}✅ Validated{RESET}", "ok"
        counts[key] += 1

        col = lambda rows: ",".join(dict.fromkeys(r["id"] for r in rows)) or "—"
        print(f"{rid:<9}{col(r_reqs):<9}{col(r_ctrls):<10}{col(r_tasks):<10}{col(r_vals):<9}{arch:<5}{status}")
        for g in dict.fromkeys(gaps):
            print(f"{RED}         └─ {g}{RESET}")

    if problems:
        print()
        for p in dict.fromkeys(problems):
            print(f"{RED}❌ {p}{RESET}")

    write_diagram(zones, comps, flows, violations_by_flow)

    print(f"\n{len(rules)} rules: {GREEN}{counts['ok']} validated{RESET}, "
          f"{YELLOW}{counts['proposed']} proposed{RESET}, {RED}{counts['broken']} broken{RESET}")
    print(f"{DIM}Diagram regenerated: architecture-diagram.md{RESET}")
    if counts["broken"] or problems:
        print(f"{RED}{BOLD}FAIL{RESET} — the architecture or its specification breaks the constitution.\n")
        return 1
    if counts["proposed"]:
        print(f"{YELLOW}{BOLD}CONFORMANT{RESET} — architecture passes; decisions or evidence still pending.\n")
    else:
        print(f"{GREEN}{BOLD}PASS{RESET} — conformant, traced and validated.\n")
    return 0


def load(folder, label):
    SDD.mkdir(exist_ok=True)
    for f in FILES:
        shutil.copy(ROOT / "demo" / folder / f, SDD / f)
    print(f"sdd/ reset to the {label}.")
    return check()


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "check":
        sys.exit(check())
    if cmd == "reset":
        sys.exit(load("start", "demo starting state (2 rules)"))
    if cmd == "solution":
        sys.exit(load("solution", "finished RULE-03 version"))
    print(__doc__)
    sys.exit(2)
